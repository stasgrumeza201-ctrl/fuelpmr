// поиск: «пассат б6 тди», «golf 2008», «камри 3.5» — каждое слово запроса должно найтись; год сверяется с годами выпуска
const TR = { а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i', й: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sh', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya' };
const norm = s => s.toLowerCase().replace(/[а-яё]/g, c => TR[c]).replace(/,/g, '.').replace(/[^a-z0-9.]+/g, ' ').trim();
const INDEX = CARS.map(c => norm(`${c[0]} ${c[1]} ${c[2]} ${c[4]} ${c[5] === 'd' ? 'дизель diesel' : 'бензин'}`));

export function findCars(query, limit = 8) {
  const words = norm(query).split(' ').filter(Boolean);
  if (!words.length) return [];
  const years = words.filter(w => /^(19|20)\d\d$/.test(w)).map(Number);
  const rest = words.filter(w => !/^(19|20)\d\d$/.test(w));
  return CARS.filter((c, i) => {
    const [from, to] = c[3].split('-').map(Number);
    return years.every(y => y >= from && y <= to) && rest.every(w => INDEX[i].split(' ').some(t => t.startsWith(w)) || INDEX[i].includes(w));
  }).slice(0, limit);
}
